export const translate = (key, language = 'en', values = {}) => {
  const template = translations[language]?.[key] || translations.en[key] || key;
  return template.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
};

const verifiedGuidanceTranslations = {};

export const getGuidanceText = (className, field, text, language) => {
  if (language !== 'hi') return { text, missingTranslation: false };
  const translated = verifiedGuidanceTranslations[className]?.[field]?.[text];
  return translated
    ? { text: translated, missingTranslation: false }
    : { text, missingTranslation: true };
};

export const translateApiError = (message, language = 'en') => {
  if (language !== 'hi' || typeof message !== 'string') return message;
  if (message.includes('Unable to reach the AI backend')) return translate('backendApiUnavailable', language);
  if (message.includes('attention map is unavailable because the backend')) return translate('explainApiUnavailable', language);
  if (message.includes('Unable to reach the library service')) return translate('libraryApiUnavailable', language);
  if (message.includes('Unable to load scan history')) return translate('historyApiUnavailable', language);
  if (message.includes('Unable to open the saved scan')) return translate('openScanApiUnavailable', language);
  if (message.includes('Unable to save scan history')) return translate('saveScanApiUnavailable', language);
  if (message.includes('The disease library could not be loaded')) return translate('libraryLoadFailed', language);
  if (message.includes('Scan history could not be loaded')) return translate('historyLoadFailed', language);
  if (message.includes('Saved scan could not be opened')) return translate('savedScanOpenFailed', language);
  if (message.includes('PDF report could not be generated')) return translate('pdfFailed', language);
  if (message.includes('Prediction succeeded, but scan history was not saved:')) {
    return translate('historySaveFailed', language, {
      message: message.slice(message.indexOf(':') + 1).trim(),
    });
  }
  if (message.includes('The AI backend is unavailable')) return translate('backendUnavailable', language);
  return message;
};

export const translateDiseaseName = (className, language = 'en') => {
  if (language !== 'hi') return className;
  const diseaseNames = {
    Tomato_healthy: 'टमाटर — स्वस्थ',
    Potato___healthy: 'आलू — स्वस्थ',
    Pepper__bell___healthy: 'शिमला मिर्च — स्वस्थ',
  };
  return diseaseNames[className] || className;
};

export const translatePlantName = (plant, language = 'en') => {
  const keys = {
    'Bell pepper': 'plantBellPepper',
    Potato: 'plantPotato',
    Tomato: 'plantTomato',
  };
  return keys[plant] ? translate(keys[plant], language) : plant;
};
